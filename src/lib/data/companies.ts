export const COMPANIES: Record<string, Company> = Object.fromEntries(
  COMPANY_LIST.map((c) => [c.profile.ticker, c]),
);

export const DEFAULT_WATCHLIST = ["NVDA", "AAPL", "MSFT", "TSLA", "AMD", "PLTR"];
export const DEFAULT_SELECTED = "NVDA";

export function isCovered(ticker: string): boolean {
  return ticker in COMPANIES;
}

export function searchCompanies(query: string, limit = 6): Company[] {
  const q = query.trim().toUpperCase();
  if (!q) return [];
  const scored: [number, Company][] = [];
  for (const c of COMPANY_LIST) {
    const { ticker, name } = c.profile;
    const upperName = name.toUpperCase();
    let score = -1;
    if (ticker === q) score = 0;
    else if (ticker.startsWith(q)) score = 1;
    else if (upperName.startsWith(q)) score = 2;
    else if (upperName.includes(q)) score = 3;
    if (score >= 0) scored.push([score, c]);
  }
  return scored.sort((a, b) => a[0] - b[0]).slice(0, limit).map(([, c]) => c);
}

/** Months of cash runway at the current burn rate; null when operating cash flow is positive. */
export function monthsOfRunway(cash: number, quarterlyOpCashFlow: number): number | null {
  if (quarterlyOpCashFlow >= 0) return null;
  return cash / (-quarterlyOpCashFlow / 3);
}
